-- ── 4.1 Businesses Policies ───────────────────────────────────────────────────
CREATE POLICY "Allow authenticated @digitalmojo.in users to view businesses"
  ON public.businesses FOR SELECT
  TO authenticated
  USING (true);

CREATE POLICY "Allow authenticated @digitalmojo.in users to create businesses"
  ON public.businesses FOR INSERT
  TO authenticated
  WITH CHECK (true);

-- ── 4.2 Scans Policies (RBAC: Admin sees all, Member sees theirs) ────────────
CREATE POLICY "Scans: Admins see all, users see their own"
  ON public.scans FOR SELECT
  TO authenticated
  USING (
    public.is_admin()
    OR user_id = auth.uid()
    OR user_email = (auth.jwt() ->> 'email')
    OR user_id IS NULL -- Legacy/shared team scans
  );

CREATE POLICY "Scans: Authenticated users can create scans"
  ON public.scans FOR INSERT
  TO authenticated
  WITH CHECK (
    auth.uid() IS NOT NULL
    AND public.is_digitalmojo_email(auth.jwt() ->> 'email')
  );

CREATE POLICY "Scans: Admins or owners can update scan status"
  ON public.scans FOR UPDATE
  TO authenticated
  USING (
    public.is_admin()
    OR user_id = auth.uid()
  );

-- ── 4.3 Scan Points Policies ─────────────────────────────────────────────────
CREATE POLICY "Scan Points: Viewable if user can view parent scan"
  ON public.scan_points FOR SELECT
  TO authenticated
  USING (
    EXISTS (
      SELECT 1 FROM public.scans s
      WHERE s.id = scan_points.scan_id
      AND (
        public.is_admin()
        OR s.user_id = auth.uid()
        OR s.user_email = (auth.jwt() ->> 'email')
        OR s.user_id IS NULL
      )
    )
  );

CREATE POLICY "Scan Points: Insertable by authenticated members"
  ON public.scan_points FOR INSERT
  TO authenticated
  WITH CHECK (true);

-- ── 4.4 Scan Shares (Public Report Viewing) ──────────────────────────────────
-- Public token link reading allowed for clients without auth
CREATE POLICY "Public report tokens are readable by anyone with the link"
  ON public.scan_shares FOR SELECT
  TO anon, authenticated
  USING (true);

CREATE POLICY "Authenticated members can create share tokens"
  ON public.scan_shares FOR INSERT
  TO authenticated
  WITH CHECK (true);

-- Public report data access for valid tokens
CREATE POLICY "Public can view scan if share token exists"
  ON public.scans FOR SELECT
  TO anon
  USING (
    EXISTS (
      SELECT 1 FROM public.scan_shares sh
      WHERE sh.scan_id = scans.id
    )
  );

CREATE POLICY "Public can view scan points if share token exists"
  ON public.scan_points FOR SELECT
  TO anon
  USING (
    EXISTS (
      SELECT 1 FROM public.scan_shares sh
      WHERE sh.scan_id = scan_points.scan_id
    )
  );

-- ── 4.5 Scheduled Scans Policies ─────────────────────────────────────────────
CREATE POLICY "Scheduled Scans: Admins see all, users see their own"
  ON public.scheduled_scans FOR SELECT
  TO authenticated
  USING (
    public.is_admin()
    OR user_id = auth.uid()
    OR user_email = (auth.jwt() ->> 'email')
  );

CREATE POLICY "Scheduled Scans: Authenticated members can schedule"
  ON public.scheduled_scans FOR INSERT
  TO authenticated
