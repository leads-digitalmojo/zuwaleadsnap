-- Function: Check if an email belongs to the authorized organization domain
CREATE OR REPLACE FUNCTION public.is_digitalmojo_email(email text)
RETURNS boolean AS $$
BEGIN
  RETURN lower(trim(email)) LIKE '%@digitalmojo.in';
END;
$$ LANGUAGE plpgsql IMMUTABLE;

-- Function: Check if the authenticated user has Admin privileges
CREATE OR REPLACE FUNCTION public.is_admin()
RETURNS boolean AS $$
DECLARE
  claim_email text;
  user_role text;
BEGIN
  claim_email := lower(trim(coalesce(auth.jwt() ->> 'email', '')));
  user_role := coalesce(auth.jwt() -> 'user_metadata' ->> 'role', '');

  RETURN (
    claim_email IN (
      'dev@digitalmojo.in',
      'admin@digitalmojo.in',
      'nikhil@digitalmojo.in',
      'info@digitalmojo.in'
    )
    OR user_role = 'admin'
  );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER STABLE;

-- Trigger: Block non-@digitalmojo.in accounts from signing up in auth.users
CREATE OR REPLACE FUNCTION public.enforce_digitalmojo_domain()
RETURNS trigger AS $$
BEGIN
  IF NOT public.is_digitalmojo_email(NEW.email) THEN
    RAISE EXCEPTION 'Access Denied: Only official @digitalmojo.in email addresses are authorized to register.';
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS tr_enforce_digitalmojo_domain ON auth.users;
CREATE TRIGGER tr_enforce_digitalmojo_domain
  BEFORE INSERT OR UPDATE OF email ON auth.users
  FOR EACH ROW
  EXECUTE FUNCTION public.enforce_digitalmojo_domain();


