-- ── 3.1 Businesses ────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.businesses (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name         text NOT NULL,
  place_id     text,
  address      text,
  lat          double precision,
  lng          double precision,
  created_at   timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_businesses_place_id ON public.businesses(place_id);
CREATE INDEX IF NOT EXISTS idx_businesses_name ON public.businesses(name);


-- ── 3.2 Scans (Grid Scan Runs) ────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.scans (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  business_id  bigint REFERENCES public.businesses(id) ON DELETE SET NULL,
  keyword      text NOT NULL,
  center_lat   double precision NOT NULL,
  center_lng   double precision NOT NULL,
  grid_size    integer NOT NULL CHECK (grid_size IN (3, 5, 7, 9, 11, 13, 15)),
  shape        text NOT NULL CHECK (shape IN ('square', 'circle')),
  spacing_km   double precision NOT NULL CHECK (spacing_km > 0 AND spacing_km <= 50),
  total_points integer NOT NULL,
  status       text NOT NULL DEFAULT 'running' CHECK (status IN ('running', 'complete', 'error')),
  error        text,
  user_id      uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  user_email   text,
  created_at   timestamptz NOT NULL DEFAULT now(),
  completed_at timestamptz
);

CREATE INDEX IF NOT EXISTS idx_scans_user_id ON public.scans(user_id);
CREATE INDEX IF NOT EXISTS idx_scans_user_email ON public.scans(user_email);
CREATE INDEX IF NOT EXISTS idx_scans_business_id ON public.scans(business_id);
CREATE INDEX IF NOT EXISTS idx_scans_created_at ON public.scans(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_scans_status ON public.scans(status);


-- ── 3.3 Scan Points (Individual Grid Pins & Ranking Data) ─────────────────────
CREATE TABLE IF NOT EXISTS public.scan_points (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  scan_id     bigint NOT NULL REFERENCES public.scans(id) ON DELETE CASCADE,
  point_index integer NOT NULL,
  lat         double precision NOT NULL,
  lng         double precision NOT NULL,
  rank        integer,
  top_results jsonb NOT NULL DEFAULT '[]'::jsonb,
  cache_hit   boolean NOT NULL DEFAULT false,
  created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_scan_points_scan_id ON public.scan_points(scan_id);
CREATE INDEX IF NOT EXISTS idx_scan_points_rank ON public.scan_points(rank);


-- ── 3.4 Shared SERP Cache (Cross-client DataForSEO Cache) ─────────────────────
CREATE TABLE IF NOT EXISTS public.serp_cache (
  cache_key   text PRIMARY KEY,
  keyword     text NOT NULL,
  lat_rounded double precision NOT NULL,
  lng_rounded double precision NOT NULL,
  surface     text NOT NULL DEFAULT 'google_maps',
  items_json  jsonb NOT NULL,
  fetched_at  timestamptz NOT NULL DEFAULT now(),
  expires_at  timestamptz NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_serp_cache_expires ON public.serp_cache(expires_at);


-- ── 3.5 Keyword Metrics Cache (Search Volume, Competition, CPC) ───────────────
CREATE TABLE IF NOT EXISTS public.keyword_data_cache (
  keyword     text PRIMARY KEY,
  search_vol  integer,
  competition double precision,
  cpc         double precision,
  fetched_at  timestamptz NOT NULL DEFAULT now(),
  expires_at  timestamptz NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_kw_cache_expires ON public.keyword_data_cache(expires_at);


-- ── 3.6 Saved Keyword Lists ───────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.keyword_lists (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        text NOT NULL,
  business_id bigint REFERENCES public.businesses(id) ON DELETE CASCADE,
  keywords    jsonb NOT NULL DEFAULT '[]'::jsonb,
  created_by  uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_kw_lists_business ON public.keyword_lists(business_id);


-- ── 3.7 Scheduled Recurring Scans ─────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.scheduled_scans (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name         text NOT NULL,
  business_id  bigint NOT NULL REFERENCES public.businesses(id) ON DELETE CASCADE,
  keyword      text NOT NULL,
  center_lat   double precision NOT NULL,
  center_lng   double precision NOT NULL,
  grid_size    integer NOT NULL,
  shape        text NOT NULL,
  spacing_km   double precision NOT NULL,
  recurrence   text NOT NULL CHECK (recurrence IN ('weekly', 'monthly')),
  next_run_at  timestamptz NOT NULL,
  last_run_at  timestamptz,
  last_scan_id bigint REFERENCES public.scans(id) ON DELETE SET NULL,
  is_active    boolean NOT NULL DEFAULT true,
  user_id      uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  user_email   text,
  created_at   timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_scheduled_scans_next_run ON public.scheduled_scans(next_run_at) WHERE is_active = true;
CREATE INDEX IF NOT EXISTS idx_scheduled_scans_user ON public.scheduled_scans(user_id);


-- ── 3.8 Public Read-Only Report Share Tokens ─────────────────────────────────
CREATE TABLE IF NOT EXISTS public.scan_shares (
  token      text PRIMARY KEY,
  scan_id    bigint NOT NULL REFERENCES public.scans(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_scan_shares_scan ON public.scan_shares(scan_id);


-- ── 3.9 API Cost Log (Audit & Expense Tracking) ───────────────────────────────
CREATE TABLE IF NOT EXISTS public.api_cost_log (
  id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ts        timestamptz NOT NULL DEFAULT now(),
  vendor    text NOT NULL,  -- 'dataforseo_serp' | 'dataforseo_kw' | 'google_places' | 'anthropic'
  call_type text NOT NULL,
  cost_usd  numeric(10, 6) NOT NULL,
  cache_hit boolean NOT NULL DEFAULT false,
  meta      jsonb
);

CREATE INDEX IF NOT EXISTS idx_cost_log_ts ON public.api_cost_log(ts DESC);
CREATE INDEX IF NOT EXISTS idx_cost_log_vendor ON public.api_cost_log(vendor);


